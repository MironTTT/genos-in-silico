"""Физические константы PBPK-модели для эталонного взрослого человека массой 70 кг.

Единый источник значений: объёмы отсеков, органные кровотоки,
клиренсы, параметры всасывания и характеристики эталонного пациента.
Никакие магические числа в других модулях не допускаются — только
импорт из этого файла.

Источник: ICRP Publication 89 (2002), «Basic anatomical and
physiological data for use in radiological protection: reference
values». Клиренсы и константа всасывания — модельные значения для
здорового взрослого (ICRP 89 напрямую не регламентирует фармакокинетику).
"""

# --- Compartment volumes (L) ---

V_BLOOD = 5.0
"""Объём крови, л: плазма + форменные элементы, участвующие в распределении.

ICRP 89, Table 2.41: объём крови ~5.0 л для эталонного взрослого
мужчины 70 кг; значение принято как центральное для модели."""

V_LIVER = 1.8
"""Объём печени, л.

ICRP 89, Table 2.34: масса печени ~1800 г; при плотности ~1 кг/л
эффективный объём принимается равным 1.8 л."""

V_KIDNEY = 0.3
"""Объём почек, л.

ICRP 89, Table 2.34: масса обеих почек ~310 г; эффективный объём
принят равным 0.3 л."""

V_BRAIN = 1.4
"""Объём мозга, л.

ICRP 89, Table 2.34: масса мозга ~1450 г; эффективный объём принят
равным 1.4 л."""

V_GUT = 1.0
"""Эффективный объём ЖКТ, л, для моделирования всасывания.

Модельное значение: не анатомический объём ЖКТ, а объём хорошо
перемешиваемого резервуара для кинетики всасывания."""

# --- Blood flows (L/h) ---

Q_LIVER = 90.0
"""Печёночный кровоток, л/ч.

ICRP 89, Table 2.34: hepatic blood flow ~1500 мл/мин = 90 л/ч."""

Q_KIDNEY = 72.0
"""Почечный кровоток, л/ч.

ICRP 89, Table 2.34: renal blood flow ~1200 мл/мин = 72 л/ч."""

Q_BRAIN = 45.0
"""Церебральный кровоток, л/ч.

ICRP 89, Table 2.34: cerebral blood flow ~750 мл/мин = 45 л/ч."""

# --- Clearances (L/h, healthy adult) ---

CL_HEP_0 = 20.0
"""Печёночный клиренс (метаболизм), л/ч, для здоровой печени.

Модельное базовое значение; масштабируется на liver_health пациента."""

CL_REN_0 = 15.0
"""Ренальный клиренс (почечная экскреция), л/ч, для здоровых почек.

Модельное базовое значение; масштабируется на kidney_health пациента."""

CL_OTHER_0 = 5.0
"""Прочий клиренс (кожа, лёгкие и пр.), л/ч.

Модельное значение для путей элиминации вне печени и почек."""

# --- Absorption ---

KA_BASE = 1.2
"""Константа скорости всасывания из ЖКТ, 1/ч.

Модельное значение, соответствующее всасыванию с T1/2 ≈ 0.6 ч."""

# --- Reference patient ---

CARDIAC_OUTPUT_BASE = 6.5
"""Сердечный выброс эталонного взрослого, л/мин.

ICRP 89: типичный выброс покоя ~6.5 л/мин; согласован с дефолтом
Patient.cardiac_output."""

WEIGHT_REF_KG = 70.0
"""Референсная масса тела эталонного взрослого, кг.

ICRP 89: reference adult male, 70 кг."""

# --- Consistency check (guards against typos when editing) ---

# Organ flows are only part of cardiac output, so their sum must not exceed it.
assert Q_LIVER + Q_KIDNEY + Q_BRAIN <= CARDIAC_OUTPUT_BASE * 60, (
    "Сумма органных кровотоков превышает сердечный выброс: "
    f"{Q_LIVER + Q_KIDNEY + Q_BRAIN} л/ч > {CARDIAC_OUTPUT_BASE * 60} л/ч"
)

