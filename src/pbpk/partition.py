"""Коэффициенты распределения ткань/плазма (K) для PBPK-модели.

Коэффициент распределения K — безразмерная величина, показывающая,
во сколько раз концентрация препарата в ткани выше концентрации
в плазме в состоянии равновесия.

Для оценок используются упрощённые QSAR-зависимости от LogP и TPSA.

Внимание: приведённые формулы являются модельными и не взяты
из конкретной публикации. Модуль намеренно не зависит от
``src.core.Molecule``: все функции принимают простые числовые
аргументы, что делает его независимым переиспользуемым блоком.
"""


def k_liver(logp: float) -> float:
    """Коэффициент распределения печень/плазма по LogP.

    K_liver = 10 ** (0.5 * logp + 0.1)

    Печень накапливает липофильные соединения: K монотонно растёт
    с ростом LogP.
    Санити-чек: k_liver(1.0) = 10**0.6 ≈ 3.98.

    :param logp: коэффициент распределения октанол/вода (cLogP).
    :return: безразмерный коэффициент распределения печень/плазма.
    """
    return 10.0 ** (0.5 * logp + 0.1)


def k_kidney(logp: float, tpsa: float) -> float:
    """Коэффициент распределения почки/плазма по LogP и TPSA.

    K_kidney = 10 ** (0.4 * logp - 0.005 * tpsa)

    Почки умеренно накапливают липофилы; высокая полярность (TPSA)
    снижает распределение.
    Санити-чек: k_kidney(2.0, 60.0) = 10**0.5 ≈ 3.16.

    :param logp: коэффициент распределения октанол/вода (cLogP).
    :param tpsa: топологическая полярная площадь поверхности, Å².
    :return: безразмерный коэффициент распределения почки/плазма.
    """
    return 10.0 ** (0.4 * logp - 0.005 * tpsa)


def k_brain(logp: float, tpsa: float) -> float:
    """Коэффициент распределения мозг/плазма по LogP и TPSA.

    K_brain = 10 ** (0.3 * logp - 0.01 * tpsa)

    Мозг — липофильная ткань, но гематоэнцефалический барьер (ГЭБ)
    ограничивает крупные полярные молекулы; отдельно от этого
    коэффициента существует проницаемость BBB (будет в Шаге 5).
    Здесь K_brain описывает равновесное распределение, а не кинетику
    пересечения барьера.
    Санити-чек: k_brain(2.0, 60.0) = 10**0.0 = 1.0.

    :param logp: коэффициент распределения октанол/вода (cLogP).
    :param tpsa: топологическая полярная площадь поверхности, Å².
    :return: безразмерный коэффициент распределения мозг/плазма.
    """
    return 10.0 ** (0.3 * logp - 0.01 * tpsa)